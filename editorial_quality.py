"""Fail-closed structural checks for automatically published editorial copy."""
import re

def validate_article(body, *, source_url, score):
    if score is None or not 7 <= score <= 10:
        raise ValueError('Story did not meet the minimum editorial relevance score')
    if source_url not in body:
        raise ValueError('Article is missing the selected source URL')
    words = re.findall(r"\b[\w'-]+\b", body)
    if not 200 <= len(words) <= 1400:
        raise ValueError('Edited article must contain 200–1400 words')
    for phrase in ('The headline is the easy part.', 'The common mistake is treating this as a standalone news item'):
        if phrase.lower() in body.lower():
            raise ValueError('Editor returned the canned seed template rather than a story-specific article')
    if re.search(r'the headline[^.!?\n]{0,160}is the easy part|this is really an ownership problem|the dashboard[^.!?\n]{0,100}is not the control',body,re.I):
        raise ValueError('Editor recycled stock voice-profile slogans')
    if re.search(r'(?im)^\s*(?:Generated by|Pipeline note|Draft model)\s*:',body):
        raise ValueError('Article contains a prohibited pipeline attribution footer')
    if re.search(r'<\s*(?:script|iframe|object|embed)\b',body,re.I):
        raise ValueError('Article contains active HTML')
